  modules.claudeModes = new ClaudeModes(modules, deps);
  modules.participantRequests = new ParticipantRequests(modules, deps);
  modules.requestRecovery = new RequestRecovery(modules, deps);
  modules.requesterResumes = new RequesterResumes(modules, deps);
  modules.delegation = new Delegation(modules, deps);
  modules.inferredRequests = new InferredRequests(modules, deps);
  modules.accord = new ChatAccord(modules, deps);
  modules.compaction = new Compaction(modules, deps);
  modules.memberCompaction = new MemberCompaction(modules, deps);
  modules.selfCompaction = new SelfCompaction(modules, deps);
  modules.selfCompactionResumes = new SelfCompactionResumes(modules, deps);
  modules.scheduledTasks = new ScheduledTasks(modules, deps);
  modules.chatReadTools = new ChatReadTools(modules, deps);
  modules.chatPostTools = new ChatPostTools(modules, deps);
  modules.attachments = new ChatAttachments(modules, deps);
  modules.messageSending = new MessageSending(modules, deps);
  modules.participantBatch = new ParticipantBatch(modules);
  modules.participantTurn = new ParticipantTurn(modules, deps);
  modules.turnQueue = new TurnQueue(modules);
  modules.pendingReplies = new PendingReplies(modules, deps);
  modules.selfResumedTurns = new SelfResumedTurns(modules, deps);
  modules.backgroundTasks = new BackgroundTasks(deps);
  modules.promptSuggestions = new PromptSuggestions(modules);
  modules.turnPrompt = new TurnPrompt(modules, deps);
  modules.promptContext = new PromptContext(modules, deps);
  modules.memberSessions = new MemberSessions(modules, deps);
  modules.appMcpGrants = new AppMcpGrants(deps);
  modules.executorLeases = new ExecutorLeases();
  modules.autoWatch = new AutoWatch(modules, deps);
  modules.choiceAnswers = new ChoiceAnswers(modules, deps);
